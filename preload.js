const { contextBridge, ipcRenderer, clipboard, webUtils } = require('electron');

contextBridge.exposeInMainWorld('younesh', {
  loadStore: () => ipcRenderer.invoke('store:load'),
  saveStore: (data) => ipcRenderer.invoke('store:save', data),
  listShells: () => ipcRenderer.invoke('shells:list'),
  info: () => ipcRenderer.invoke('app:info'),
  pickFolder: (defaultPath) => ipcRenderer.invoke('dialog:folder', defaultPath),
  spawn: (opts) => ipcRenderer.invoke('pty:spawn', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (fn) => ipcRenderer.on('pty:data', (_e, id, data) => fn(id, data)),
  onExit: (fn) => ipcRenderer.on('pty:exit', (_e, id, code) => fn(id, code)),
  loadBuffers: () => ipcRenderer.invoke('buffers:load'),
  saveBuffers: (data) => ipcRenderer.sendSync('buffers:save', data),
  gitBranches: (dirs) => ipcRenderer.invoke('git:branches', dirs),
  sbxList: () => ipcRenderer.invoke('sbx:list'),
  pickFile: (defaultPath) => ipcRenderer.invoke('dialog:file', defaultPath),
  sshConfig: () => ipcRenderer.invoke('ssh:config'),
  tunnelStart: (id, args) => ipcRenderer.invoke('tunnel:start', id, args),
  tunnelWrite: (id, data) => ipcRenderer.send('tunnel:write', id, data),
  tunnelStop: (id) => ipcRenderer.send('tunnel:stop', id),
  onTunnelData: (fn) => ipcRenderer.on('tunnel:data', (_e, id, data) => fn(id, data)),
  onTunnelExit: (fn) => ipcRenderer.on('tunnel:exit', (_e, id, code) => fn(id, code)),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  onUpdateReady: (fn) => ipcRenderer.on('update:ready', (_e, version) => fn(version)),
  openJson: () => ipcRenderer.invoke('file:openJson'),
  saveJson: (name, text) => ipcRenderer.invoke('file:saveJson', name, text),
  setChrome: (opts) => ipcRenderer.send('win:chrome', opts),
  flash: () => ipcRenderer.send('win:flash'),
  focusWindow: () => ipcRenderer.send('win:focus'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  copy: (text) => clipboard.writeText(text),
  paste: () => clipboard.readText(),
});
